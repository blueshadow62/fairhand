export const DICT: Record<Language, Record<Key, string>> = { ko, en };

let current: Language = 'ko';

/** 설정을 읽은 뒤 한 번 부른다. 그 뒤의 t()가 이 언어로 나온다 */
export function setLanguage(lang: Language): void {
  current = lang;
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}
export const language = (): Language => current;
/** toLocaleString 등에 쓰는 지역 코드 */
export const locale = (): string => (current === 'en' ? 'en-US' : 'ko-KR');

/** 화면 글. 사전에 없는 영어 글은 한국어로 대신한다 */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const s = DICT[current][key] ?? ko[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}
